/** Nombres con ícono propio, en el orden del selector de íconos (los de la base legacy primero). */
export const MATERIAL_ICON_NAMES: readonly string[] = Object.keys(MATERIAL_TO_LUCIDE);

/** true si el nombre tiene ícono propio (si no, el menú muestra el punto genérico). */
export function hasMenuIcon(name: string | null | undefined): boolean {
  return !!name && name.trim().toLowerCase() in MATERIAL_TO_LUCIDE;
}

/** Ícono lucide para un nombre de Material Icons; desconocido o vacío → punto. */
export function menuIcon(name: string | null | undefined): LucideIcon {
  return (name && MATERIAL_TO_LUCIDE[name.trim().toLowerCase()]) || CircleDot;
}
